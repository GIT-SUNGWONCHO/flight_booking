#    'full'  17단계 전부(결제까지). 쓰지 않는다.
#
#  **실전이 끝나면 다시 'dry' 로 돌려놓는다.**
#  깜빡해도 daily.py 가 목표일(CALENDAR.md)이 아니면 dry 로 내린다 - 하지만
